import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import {
	apiOperations,
	getApiOperationPathParams,
	listApiOperationPaths,
} from '../packages/worker/src/open-api/operations.ts'

const outputPath = resolve(
	import.meta.dirname,
	'../packages/cli/src/generated/openapi-routes.ts',
)

type BakedRoute = {
	operationId: string
	method: string
	pathTemplate: string
	pathParamNames: Array<string>
}

export function bakedRoutesFromOperations(): Array<BakedRoute> {
	const routes: Array<BakedRoute> = []
	for (const operation of apiOperations) {
		for (const pathTemplate of listApiOperationPaths(operation)) {
			routes.push({
				operationId:
					pathTemplate === operation.path
						? operation.operationId
						: `${operation.operationId}ByPath`,
				method: operation.method,
				pathTemplate,
				pathParamNames: getApiOperationPathParams(pathTemplate),
			})
		}
	}
	routes.sort((left, right) =>
		left.operationId.localeCompare(right.operationId),
	)
	return routes
}

function renderRoute(route: BakedRoute): string {
	const params =
		route.pathParamNames.length === 0
			? '[]'
			: `[${route.pathParamNames.map((name) => `'${name}'`).join(', ')}]`
	return [
		'\t{',
		`\t\toperationId: '${route.operationId}',`,
		`\t\tmethod: '${route.method}',`,
		`\t\tpathTemplate: '${route.pathTemplate}',`,
		`\t\tpathParamNames: ${params},`,
		'\t},',
	].join('\n')
}

export function renderBakedOpenApiRoutes(routes: Array<BakedRoute>): string {
	return `// Generated by tools/generate-cli-openapi-client.ts. Do not edit.
export const bakedOpenApiRoutes = [
${routes.map(renderRoute).join('\n')}
]
`
}

const rendered = renderBakedOpenApiRoutes(bakedRoutesFromOperations())
const check = process.argv.includes('--check')
if (check) {
	const current = readFileSync(outputPath, 'utf8')
	if (current !== rendered) {
		console.error(
			'packages/cli/src/generated/openapi-routes.ts is stale. Run node --experimental-strip-types tools/generate-cli-openapi-client.ts',
		)
		process.exit(1)
	}
} else {
	mkdirSync(resolve(outputPath, '..'), { recursive: true })
	writeFileSync(outputPath, rendered)
}
